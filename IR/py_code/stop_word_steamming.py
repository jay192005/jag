import nltk
import string
from nltk.corpus import stopwords
from nltk.tokenize import word_tokenize
from nltk.stem import PorterStemmer

nltk.download('punkt') #tokenize data
nltk.download('punkt_tab')#newer tokenize data
nltk.download('stopwords')#it has stop words

text = """
Information Retrieval is an important subject in computer science.
Students are learning different techniques of searching and retrieving
relevant information from documents. The students are studying and
playing with different examples.
"""

# Step 4: Convert text into lowercase
text = text.lower()

# Step 5: Tokenization
words = word_tokenize(text)

print("Original Tokens:")
print(words)

# Step 6: Remove punctuation
words = [
    word for word in words
    if word not in string.punctuation
]
print(words)

# Step 7: Remove stop words
stop_words = set(stopwords.words('english'))

filtered_words = [
    word for word in words
    if word not in stop_words
]

print("\nAfter Stop Word Removal:")
print(filtered_words)

ps = PorterStemmer()

stemmed_words = [
    ps.stem(word) for word in filtered_words
]

print("\nAfter Stemming:")
print(stemmed_words)

# Step 9: Display final preprocessed text
final_text = " ".join(stemmed_words)

print("\nFinal Preprocessed Text:")
print(final_text)

