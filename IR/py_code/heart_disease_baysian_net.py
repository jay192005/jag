# Assignment No. 03
# Title: Bayesian Network for Heart Disease Diagnosis

import pandas as pd
from pgmpy.models import DiscreteBayesianNetwork
from pgmpy.inference import VariableElimination

# Step 1: Load the Dataset

df = pd.read_csv(r"/content/heart-disease-data.csv")

# Step 2: Preprocess Data (Convert continuous numbers into categories)
discretize_rules = {
    'age': ([0, 40, 60, 100], ['Young', 'Middle', 'Senior']),
    'trestbps': ([0, 120, 140, 250], ['Low', 'Normal', 'High']),
    'chol': ([0, 200, 240, 600], ['Normal', 'Borderline', 'High']),
    'thalach': ([0, 100, 150, 250], ['Low', 'Medium', 'High']),
    'oldpeak': ([-1, 1, 2, 10], ['Low', 'Medium', 'High'])
}

for column, (bins, labels) in discretize_rules.items():
    df[column] = pd.cut(df[column], bins=bins, labels=labels)

# Clean up remaining data and convert everything to strings
df = df.dropna().astype(str)

# Step 3: Construct the Bayesian Network
# Creates one-way arrows from the 'target' (Disease) to all 13 symptoms
symptoms = [col for col in df.columns if col != 'target']
edges = [('target', symptom) for symptom in symptoms]

model = DiscreteBayesianNetwork(edges)

# Step 4: Train the Model (Learn the Probabilities)
# The library now uses DiscreteMLE() by default automatically
model.fit(df)
print("Model Trained Successfully!\n")

# Step 5: Perform Bayesian Inference (Predict for a sample patient)
inference = VariableElimination(model)

# Define a hypothetical patient based on some symptoms
sample_patient = {
    'age': 'Senior',
    'sex': '1',       # 1 = Male
    'cp': '3',        # Chest pain type 3
    'chol': 'High',
    'thalach': 'Low'
}

print("Patient Evidence:", sample_patient)
print("\nPredicting Heart Disease Probability...")

# Query the network
result = inference.query(variables=['target'], evidence=sample_patient)
print(result)

