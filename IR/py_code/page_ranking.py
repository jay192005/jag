# Assignment No. 05
# Title: Implement PageRank Algorithm

import networkx as nx


edges = [
    ('A', 'B'),
    ('A', 'C'),
    ('B', 'D'),
    ('C', 'A'),
    ('C', 'B'),
    ('C', 'D'),
    ('D', 'C')
]

# Step 2: Create a directed graph
G = nx.DiGraph()
G.add_edges_from(edges)

# Step 3: Calculate PageRank scores
pagerank_scores = nx.pagerank(G, alpha=0.85)

# Step 4: Display PageRank scores in descending order
print("--- PAGERANK SCORES ---")

for node, score in sorted(
    pagerank_scores.items(),
    key=lambda x: x[1],
    reverse=True
):
    print(f"Page {node} : {score:.4f}")

# Step 5: Find the most important page
highest_page = max(pagerank_scores, key=pagerank_scores.get)

print(f"\nMost Important Page: Page {highest_page}")